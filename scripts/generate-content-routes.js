#!/usr/bin/env node
// Map source fragments only to existing finished pages, never guessed targets.
const fs = require('node:fs');
const path = require('node:path');
const ROOT = path.resolve(__dirname, '..');
function generateContentRoutes(root = ROOT) {
  const routes = {};
  for (const directory of ['content', 'content/artikel']) {
    const folder = path.join(root, directory);
    if (!fs.existsSync(folder)) continue;
    for (const item of fs.readdirSync(folder, { withFileTypes: true }).sort((a,b)=>a.name.localeCompare(b.name))) {
      if (!item.isFile() || !item.name.endsWith('.html')) continue;
      const relative = `${directory}/${item.name}`.slice('content/'.length);
      const target = path.join(root, relative);
      if (!fs.existsSync(target) || !fs.statSync(target).isFile()) continue;
      const html = fs.readFileSync(target, 'utf8');
      const canonical = html.match(/<link\b[^>]*\brel=["']canonical["'][^>]*\bhref=["']([^"']+)["']/i)?.[1];
      if (!canonical) throw new Error(`Missing canonical for ${relative}`);
      const url = new URL(canonical);
      if (url.origin !== 'https://aquaristik-zentrum.com') throw new Error(`Invalid canonical for ${relative}`);
      routes[`/${directory}/${item.name.slice(0,-5)}`] = url.pathname;
    }
  }
  return routes;
}
function writeContentRoutes(root = ROOT) {
  const routes = generateContentRoutes(root);
  fs.mkdirSync(path.join(root, 'data'), { recursive: true });
  fs.writeFileSync(path.join(root, 'data/public-content-routes.mjs'), '// Generated by scripts/generate-content-routes.js.\nexport default '+JSON.stringify(routes,null,2)+';\n');
  console.log(`Content redirects: ${Object.keys(routes).length} finished pages`);
}
if (require.main === module) writeContentRoutes();
module.exports = { generateContentRoutes, writeContentRoutes };
