#!/usr/bin/env node
// Generates data/public-content-routes.mjs mapping source-fragment paths to
// public pages. URL consolidation: every target is a trailing-slash URL.
const fs = require('node:fs');
const path = require('node:path');

function writeContentRoutes(root = ROOT) {
  const contentDir = path.join(root, 'content');
  const routes = new Map();
  if (fs.existsSync(contentDir)) {
    for (const name of fs.readdirSync(contentDir, { withFileTypes: true })) {
      if (name.isFile() && name.name.endsWith('.html')) {
        const base = name.name.slice(0, -5);
        const publicFile = path.join(root, `${base}.html`);
        if (fs.existsSync(publicFile)) routes.set(`/content/${base}`, `/${base}/`);
      }
    }
    const artikelDir = path.join(contentDir, 'artikel');
    if (fs.existsSync(artikelDir)) {
      for (const name of fs.readdirSync(artikelDir, { withFileTypes: true })) {
        if (name.isFile() && name.name.endsWith('.html')) {
          const base = name.name.slice(0, -5);
          const publicFile = path.join(root, 'artikel', `${base}.html`);
          if (fs.existsSync(publicFile)) routes.set(`/content/artikel/${base}`, `/artikel/${base}/`);
        }
      }
    }
  }
  const sorted = [...routes.entries()].sort((a, b) => a[0].localeCompare(b[0]));
  let out = '// Generated by scripts/generate-content-routes.js.\n';
  out += '// All targets are canonical trailing-slash URLs.\n';
  out += 'export default {\n';
  for (const [source, target] of sorted) out += `  "${source}": "${target}",\n`;
  out += '};\n';
  fs.writeFileSync(path.join(root, 'data', 'public-content-routes.mjs'), out, 'utf8');
  console.log(`Content redirects: ${sorted.length} finished pages`);
}
if (require.main === module) writeContentRoutes();
module.exports = { writeContentRoutes };
